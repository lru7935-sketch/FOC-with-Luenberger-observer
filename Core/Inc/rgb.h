/**
  ******************************************************************************
  * @file    rgb.h
  * @brief   WS2812 灯珠驱动（TIM3 CH2 + DMA）
  ******************************************************************************
  */

#ifndef __RGB_H_
#define __RGB_H_

/*============================================================================*/
/*                                   头文件                                   */
/*============================================================================*/
#include "tim.h"

/*============================================================================*/
/*                                  配置参数                                  */
/*============================================================================*/
#define RGB_TIM              htim3              /* 输出所用定时器 */
#define RGB_CHANNEL          TIM_CHANNEL_2      /* 输出所用通道 */
#define RGB_BUF_LEN          260                /* DMA 缓冲长度 */
/* 编码方式：PWM 周期 1200 ns（17 分频，ARR = 12）
 *   1 码 -> 比较值 6（高电平 600 ns）
 *   0 码 -> 比较值 3（高电平 300 ns）
 * 缓冲末尾 236 个 0 构成 283.2 µs 低电平复位帧，整帧 260 * 1.2 µs = 312 µs */
#define RGB_PI               3.1415926f         /* 色环换算用 */

/*============================================================================*/
/*                                  类型定义                                  */
/*============================================================================*/
typedef enum
{
    RGB_RED   = 0,
    RGB_GREEN = 1,
    RGB_BLUE  = 2
} RGB_Color_Typedef;

/*============================================================================*/
/*                                  对外 API                                  */
/*============================================================================*/
void              RGB_Init(void);
HAL_StatusTypeDef RGB_Set_Color(uint8_t r, uint8_t g, uint8_t b);
void              RGB_Set_Red(uint8_t brightness);
void              RGB_Set_Green(uint8_t brightness);
void              RGB_Set_Blue(uint8_t brightness);
void              RGB_Show(uint8_t brightness);      /* 色环循环，亮度 0~255 */
void              RGB_Close(void);
void              RGB_Blink(RGB_Color_Typedef color, uint8_t brightness, uint32_t interval);

#endif /* __RGB_H_ */
